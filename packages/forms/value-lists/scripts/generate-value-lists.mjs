#!/usr/bin/env node

// Emits value list modules from source data, for this package or for any form package that owns lists of its own.
//
// Each list is written as a flat array of rows rather than as objects, and a child list's rows carry the value of
// the parent option they hang off rather than being grouped underneath it. The row is the compact half of the
// deal: an option spelled out in full costs about forty-nine bytes to express twenty bytes of data, almost all of
// it the same `{ value: "", description: "" },` scaffolding repeated once per row.
//
// The lists to emit are declared by a manifest at <data>/lists.json, so this script carries no knowledge of which
// package is running it:
//
//     [{ "source": "counties.json", "output": "counties.ts", "export": "counties", "doc": "..." }]
//
// Usage: generate-value-lists [--data ./data] [--out ./src/generated] [--row-import <specifier>]
//
// Paths are resolved against the working directory, so a package runs it from its own root. `--row-import` names
// where the emitted files reach `ValueListRow`: this package uses a relative path into its own models, and a form
// package uses the package name.

import { mkdir, readFile, writeFile } from "node:fs/promises";
import { join, resolve } from "node:path";

const defaults = {
    data: "./data",
    out: "./src/generated",
    "row-import": "@forms/value-lists"
};

/** Reads the command line into an options object, falling back to the defaults for anything not given. */
function parseArguments(argv) {
    const options = { ...defaults };

    for (let index = 0; index < argv.length; index++) {
        const name = argv[index].replace(/^--/, "");

        if (!(name in defaults)) {
            throw new Error(`Unknown option '${argv[index]}'. Expected one of: ${Object.keys(defaults).map(key => `--${key}`).join(", ")}.`);
        }

        const value = argv[++index];

        if (value === undefined) {
            throw new Error(`Option '${argv[index - 1]}' expects a value.`);
        }

        options[name] = value;
    }

    return options;
}

/** Renders a list's doc comment, on one line where it fits on one and as a block where it does not. */
function renderDoc(doc) {
    const lines = Array.isArray(doc) ? doc : [doc];

    // a blank line separating paragraphs is emitted as a bare ` *`, so the output carries no trailing whitespace
    return lines.length === 1
        ? `/** ${lines[0]} */`
        : ["/**", ...lines.map(line => line ? ` * ${line}` : " *"), " */"].join("\n");
}

/** Renders one option as a row: the value, the description, and, on a child list, the parent's value. */
function renderRow({ value, description, parentValue }) {
    const fields = parentValue === undefined
        ? [value, description]
        : [value, description, parentValue];

    // JSON.stringify carries the escaping, which the data needs: a handful of descriptions contain quotes
    return `    [${fields.map(field => JSON.stringify(field)).join(", ")}]`;
}

// the value list indexes scope a child's key by joining it to the parent's value with a pipe, so a pipe inside a
// code or description would let two different pairs collide on a single key. No row in the recovered data carries
// one; this is what keeps that true of the next data drop as well.
const forbiddenCharacters = /[|\r\n\t]/;

/** Fails rather than emitting a row whose fields would not survive the round trip. */
function assertRow(sourceName, option, index) {
    for (const [field, text] of Object.entries(option)) {
        if (typeof text !== "string") {
            throw new Error(`${sourceName} row ${index}: '${field}' is ${typeof text}, expected a string.`);
        }

        if (forbiddenCharacters.test(text)) {
            throw new Error(`${sourceName} row ${index}: '${field}' contains a pipe, tab or line break, which the value list indexes reserve.`);
        }
    }

    if (!option.value && !option.description) {
        throw new Error(`${sourceName} row ${index}: an option with neither a value nor a description is no option at all.`);
    }
}

async function generate(list, options) {
    const source = JSON.parse(await readFile(resolve(options.data, list.source), "utf8"));

    source.forEach((option, index) => assertRow(list.source, option, index));

    // the type annotation is load-bearing: without it TypeScript infers the literal type of every row and writes
    // the whole list into the emitted .d.ts a second time
    const contents = [
        `// Generated by generate-value-lists from ${options.data.replace(/^\.\//, "")}/${list.source} - do not edit.`,
        "",
        // the import is type-only and must stay that way: a value import of anything outside ./generated is an
        // edge the bundler follows, and these modules are only ever meant to be reached through a dynamic import
        `import type { ValueListRow } from "${options["row-import"]}";`,
        "",
        renderDoc(list.doc),
        `export const ${list.export}: ReadonlyArray<ValueListRow> = [`,
        source.map(renderRow).join(",\n"),
        "];",
        ""
    ].join("\n");

    await writeFile(resolve(options.out, list.output), contents, "utf8");

    return { name: list.output, rows: source.length, bytes: Buffer.byteLength(contents, "utf8") };
}

async function main() {
    const options = parseArguments(process.argv.slice(2));
    const manifestPath = join(resolve(options.data), "lists.json");
    const lists = JSON.parse(await readFile(manifestPath, "utf8"));

    // a package generating its lists for the first time has no output directory yet, and the ENOENT that
    // writeFile would raise reads like a broken tool rather than a missing folder
    await mkdir(resolve(options.out), { recursive: true });

    for (const list of lists) {
        const result = await generate(list, options);

        console.log(`${result.name.padEnd(22)} ${String(result.rows).padStart(5)} rows  ${String(result.bytes).padStart(7)} bytes`);
    }
}

try {
    await main();
} catch (error) {
    // this runs through a bin shim, where an unhandled rejection prints a stack that buries the actual problem
    console.error(`generate-value-lists: ${error.message}`);
    process.exitCode = 1;
}
